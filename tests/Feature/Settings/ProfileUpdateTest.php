<?php

use App\Models\User;
use Database\Seeders\RoleSeeder;

// El panel /settings/* usa el layout del panel admin y ahora está
// reservado a superadmin/admin/editor (los lectores públicos gestionan su
// cuenta en /perfil/{username}/settings, ver tests/Feature/Public/ProfileSettingsTest.php).
beforeEach(function () {
    $this->seed(RoleSeeder::class);
});

function staffUser(): User
{
    $user = User::factory()->create();
    $user->assignRole('editor');

    return $user;
}

test('profile page is displayed', function () {
    $user = staffUser();

    $response = $this
        ->actingAs($user)
        ->get(route('profile.edit'));

    $response->assertOk();
});

test('profile information can be updated', function () {
    $user = staffUser();

    $response = $this
        ->actingAs($user)
        ->patch(route('profile.update'), [
            'name' => 'Test User',
            'email' => 'test@example.com',
        ]);

    $response
        ->assertSessionHasNoErrors()
        ->assertRedirect(route('profile.edit'));

    $user->refresh();

    expect($user->name)->toBe('Test User');
    expect($user->email)->toBe('test@example.com');
    expect($user->email_verified_at)->toBeNull();
});

test('email verification status is unchanged when the email address is unchanged', function () {
    $user = staffUser();

    $response = $this
        ->actingAs($user)
        ->patch(route('profile.update'), [
            'name' => 'Test User',
            'email' => $user->email,
        ]);

    $response
        ->assertSessionHasNoErrors()
        ->assertRedirect(route('profile.edit'));

    expect($user->refresh()->email_verified_at)->not->toBeNull();
});

test('user can delete their account', function () {
    $user = staffUser();

    $response = $this
        ->actingAs($user)
        ->delete(route('profile.destroy'), [
            'password' => 'password',
        ]);

    $response
        ->assertSessionHasNoErrors()
        ->assertRedirect(route('home'));

    $this->assertGuest();
    expect($user->fresh())->toBeNull();
});

test('correct password must be provided to delete account', function () {
    $user = staffUser();

    $response = $this
        ->actingAs($user)
        ->from(route('profile.edit'))
        ->delete(route('profile.destroy'), [
            'password' => 'wrong-password',
        ]);

    $response
        ->assertSessionHasErrors('password')
        ->assertRedirect(route('profile.edit'));

    expect($user->fresh())->not->toBeNull();
});

test('a public reader without a staff role cannot reach the admin settings panel', function () {
    $reader = User::factory()->create();

    $this->actingAs($reader)->get(route('profile.edit'))->assertForbidden();
});
